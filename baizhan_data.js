// 此数据仅按 topicId 挂载字段，不新增知识点

// 挂载函数：把百斩字段合并进知识树
function enrichKnowledgeTree(tree) {
  if (!tree) return tree;
  tree.forEach(m => {
    m.topics.forEach(t => {
      const d = BAIZHAN_DATA[t.id];
      if (d) {
        t.cardType = d.cardType || t.cardType || 'A';
        t.scene = d.scene || t.scene || t.summary;
        t.analogy = d.analogy || '';
        t.operationSteps = d.operationSteps || [];
        if (d.trapQuestions) t.trapQuestions = d.trapQuestions;
      } else {
        // 兜底：未配置的知识点给默认字段
        t.cardType = t.cardType || (t.questions && t.questions.some(q => /检验|回归|分析/.test(q.q)) ? 'B' : 'A');
        t.scene = t.scene || t.summary;
        t.analogy = t.analogy || (t.cardType === 'C' ? '注意区分易混淆概念，这是统计陷阱高发区。' : '结合医学场景理解该方法的核心逻辑与适用条件。');
        t.operationSteps = t.operationSteps || ['SPSS：分析→相应菜单', 'R语言：对应函数', '查看P值与效应量'];
      }
    });
  });
  return tree;
}